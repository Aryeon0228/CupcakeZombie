// Assemble src/levels.js from plan.js + generated boards in genout/plan (shared with v2 tools dir)
const fs = require('fs'), path = require('path');
const { CH } = require('./plan.js');
const EN = require('./en.js');
// intro objects are shared between plan.js entries; find which English intro matches by Korean title
const G = require('./gen.js');
const genDir = require('path').join(__dirname, 'genout/plan');
const LEVELS = [], CHAPTERS = [];
for (const ch of CH) {
  const from = LEVELS.length;
  ch.stages.forEach((st, i) => {
    let grid, customers = [];
    if (st.hand === 'heart') grid = ['.oo.oo.', 'ooooooo', '.ooooo.', '..ooo..', '...o...'];
    else {
      const f = path.join(genDir, `${ch.no}-${i + 1}.json`);
      const d = fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : null;
      if (!d) { if (process.env.STRICT) throw new Error('missing ' + f); console.log('  (placeholder for ' + st.name + ')'); grid = ['oxo.o', 'x.xoo', 'ooxx.', '.ooxo']; customers = []; }
      else { grid = d.grid; customers = d.customers || []; }
    }
    const en = EN.stages[`${ch.no}-${i + 1}`];
    if (!en) throw new Error('no English for ' + ch.no + '-' + (i + 1));
    const lvl = { name: st.name, name_en: en[0], spores: st.spores, tip: st.tip, tip_en: en[1], grid, customers };
    if (st.intro) {
      const k = st.intro.kind === 'type' ? st.intro.t : st.intro.kind === 'spores' ? (st.intro.title === '포자 두 개' ? 'two' : 'three') : st.intro.kind;
      const ie = EN.intros[k];
      if (!ie) throw new Error('no English intro for ' + k);
      lvl.intro = { ...st.intro, title_en: ie.title, text_en: ie.text };
      if (ie.tag) lvl.intro.tag_en = ie.tag;
    }
    const a = G.analyze(lvl);
    if (!a.first) throw new Error('unsolvable ' + st.name);
    console.log(`${String(LEVELS.length + 1).padStart(2)} ${ch.no}-${i + 1} ${st.name.padEnd(9)} sp=${st.spores} n=${a.cupcakes} first=${a.first}/${a.total} greedy=${a.greedyWins} waves=${a.maxWaves} surv=${a.minSurvivorsWrong}`);
    LEVELS.push(lvl);
  });
  CHAPTERS.push({ no: ch.no, name: ch.name, name_en: EN.chapters[ch.no], from, to: LEVELS.length - 1 });
}
const DAILY = JSON.parse(fs.readFileSync(path.join(genDir, 'daily.json'), 'utf8')).filter(Boolean).map(d => ({ grid: d.grid, customers: d.customers, spores: d.spores }));
fs.writeFileSync(path.join(__dirname, '../src/levels.js'),
  '// generated by tools/pick.js\nconst LEVELS = ' + JSON.stringify(LEVELS) + ';\nconst CHAPTERS = ' + JSON.stringify(CHAPTERS) + ';\nconst DAILY = ' + JSON.stringify(DAILY) + ';\nif (typeof module !== "undefined") module.exports = { LEVELS, CHAPTERS, DAILY };\n');
console.log('levels', LEVELS.length, 'daily', DAILY.length);
